#!/usr/bin/env python3
"""Generate a random synchronous gate-level netlist for benchmarking logicsim.

The circuit is a layered random logic cloud with feedback through flip-flops:

* primary inputs `clk`, `rst` and `in[0..I-1]`;
* combinational gates arranged in `--depth` levels; each gate reads 1-4 nets from earlier
  levels (biased towards the previous few levels), primary inputs or flip-flop outputs;
* `--ff-ratio` of the gates are D flip-flops (posedge clk, async reset) whose D comes from a
  random combinational net and whose Q feeds back into the logic;
* primary outputs `out[0..O-1]` are taken from the last level.

Output is deterministic for a given seed. All gates are zero-delay by default, so every input
change settles through delta cycles within one time step.

    python3 benchmarks/gen_netlist.py --gates 10000 --out benchmarks/medium_10k.v
"""

from __future__ import annotations

import argparse
import random
import sys

GATE_MIX = [("and", 20), ("or", 20), ("nand", 15), ("nor", 15), ("xor", 10), ("xnor", 5), ("not", 10), ("buf", 5)]


def generate(gates: int, seed: int, ff_ratio: float, depth: int | None, inputs: int | None,
             outputs: int | None, delay: int) -> str:
    rng = random.Random(seed)
    n_ff = int(gates * ff_ratio)
    n_comb = gates - n_ff
    n_in = inputs or max(8, gates // 100)
    n_out = outputs or max(4, gates // 200)
    depth = depth or max(4, min(32, round(gates ** 0.33)))

    types = [t for t, w in GATE_MIX for _ in range(w)]
    per_level = [n_comb // depth + (1 if i < n_comb % depth else 0) for i in range(depth)]

    sources = [f"in[{i}]" for i in range(n_in)] + [f"q[{i}]" for i in range(n_ff)]
    levels: list[list[str]] = []
    lines: list[str] = []
    dly = f" #{delay}" if delay else ""
    g = 0
    for lvl, count in enumerate(per_level):
        names = []
        for _ in range(count):
            kind = rng.choice(types)
            fanin = 1 if kind in ("not", "buf") else rng.choice((2, 2, 2, 3, 3, 4))
            ins = []
            for _ in range(fanin):
                # Mostly the previous three levels, sometimes any source: keeps the logic deep.
                if lvl > 0 and rng.random() < 0.85:
                    pick_from = levels[rng.randint(max(0, lvl - 3), lvl - 1)]
                else:
                    pick_from = sources
                ins.append(rng.choice(pick_from))
            out = f"n[{g}]"
            lines.append(f"  {kind}{dly} g{g} ({out}, {', '.join(ins)});")
            names.append(out)
            g += 1
        levels.append(names)

    comb_nets = [n for lvl in levels for n in lvl]
    ff_lines = []
    for i in range(n_ff):
        d = rng.choice(comb_nets)
        ff_lines.append(f"  dff{dly} ff{i} (.Q(q[{i}]), .D({d}), .CLK(clk), .RST(rst));")

    last = levels[-1]
    out_lines = [f"  buf ob{i} (out[{i}], {last[i % len(last)]});" for i in range(n_out)]

    header = [
        f"// Random benchmark netlist: {gates} gates ({n_comb} combinational + {n_ff} flip-flops"
        f" + {n_out} output buffers), {depth} levels, seed {seed}.",
        "// Generated by benchmarks/gen_netlist.py.",
        f"module bench_{gates} (clk, rst, in, out);",
        "  input clk, rst;",
        f"  input [{n_in - 1}:0] in;",
        f"  output [{n_out - 1}:0] out;",
        f"  wire [{n_comb - 1}:0] n;",
    ]
    if n_ff:
        header.append(f"  wire [{n_ff - 1}:0] q;")
    return "\n".join(header + lines + ff_lines + out_lines + ["endmodule", ""])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gates", type=int, required=True, help="combinational gates + flip-flops")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--ff-ratio", type=float, default=0.1, help="fraction of gates that are flip-flops")
    ap.add_argument("--depth", type=int, help="combinational levels (default ~ gates^(1/3), max 32)")
    ap.add_argument("--inputs", type=int, help="data inputs (default gates/100, min 8)")
    ap.add_argument("--outputs", type=int, help="primary outputs (default gates/200, min 4)")
    ap.add_argument("--delay", type=int, default=0, help="delay of every gate (default 0: delta cycles only)")
    ap.add_argument("--out", help="output file (default stdout)")
    args = ap.parse_args()
    text = generate(args.gates, args.seed, args.ff_ratio, args.depth, args.inputs, args.outputs, args.delay)
    if args.out:
        with open(args.out, "w") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
